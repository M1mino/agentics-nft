def get_wallet_nfts(wallet_address: str) -> list:
    """Fetch all NFTs owned by wallet from our collection"""
    url = f"{TONCENTER_API}/nft/items"
    params = {
        "owner_address": wallet_address,
        "collection_address": COLLECTION_ADDRESS,
        "limit": 100
    }
    resp = requests.get(url, params=params, timeout=10)
    if resp.status_code != 200:
        return []
    data = resp.json()
    return data.get("nft_items", [])


def get_character_from_nft(nft_item: dict) -> str:
    """Extract character name from NFT metadata attributes"""
    metadata = nft_item.get("metadata", {})
    attributes = metadata.get("attributes", [])
    for attr in attributes:
        if attr.get("trait_type") == "Archetype":
            return attr.get("value", "Mentor-01")
    return "Mentor-01"


def get_character_prompt(wallet_address: str) -> tuple:
    """
    Returns (character_name, system_prompt, rarity) for the user's NFT.
    If no NFT found, returns free tier (limited bot).
    """
    nfts = get_wallet_nfts(wallet_address)
    if not nfts:
        return None, "You are a helpful AI assistant. Free tier — limited features.", None
    
    char_name = get_character_from_nft(nfts[0])
    char_data = CHARACTERS.get(char_name, CHARACTERS["Mentor-01"])
    return char_name, char_data["prompt"], char_data["rarity"]
